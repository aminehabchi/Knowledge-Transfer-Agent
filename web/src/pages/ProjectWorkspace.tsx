import { useEffect, useRef, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { get, post } from "../api";
import { useAuth } from "../auth";
import { HandoverView } from "../components/HandoverView";
import { Avatar, Chip, Empty, ErrorAlert, LoadError, formatDate, formatDateTime, Spinner, useLoad, usePageTitle } from "../components/ui";
import type { AssistantAnswer, DocumentSummary, Handover, HandoverSummary, Project } from "../types";

type Tab = "overview" | "assistant" | "sources";

export function ProjectWorkspace() {
  const { projectId } = useParams();
  const [tab, setTab] = useState<Tab>("assistant");
  const project = useLoad(() => get<Project>(`/api/projects/${projectId}`), [projectId]);
  const handover = useLoad(async () => {
    const list = await get<HandoverSummary[]>(`/api/handovers?projectId=${projectId}`);
    const approved = list.find((h) => h.status === "approved" || h.publication);
    return approved ? get<Handover>(`/api/handovers/${approved.id}`) : null;
  }, [projectId]);

  usePageTitle(project.data?.name);
  if (project.loading && !project.data) return <Spinner />;
  if (project.error) return <LoadError error={project.error} what="project" />;
  const p = project.data!;
  const managers = (p.members ?? []).filter((m) => m.role === "manager");

  return (
    <>
      <div className="page-head">
        <div>
          <span className="eyebrow">{p.code} · {p.clientName}</span>
          <h1>{p.name}</h1>
          <p className="lede">{p.description}</p>
        </div>
        <div className="small muted stack" style={{ gap: 2 }}>
          <span>Manager: {managers.map((m) => m.displayName).join(", ") || "-"}</span>
          {handover.data && <span>Handover v{handover.data.approvedVersion} approved {formatDate(handover.data.approvedAt)}</span>}
        </div>
      </div>

      <div className="steps" role="tablist" aria-label="Project workspace">
        {(["assistant", "overview", "sources"] as Tab[]).map((t) => (
          <button key={t} role="tab" className="step" aria-selected={tab === t} aria-current={tab === t ? "step" : undefined} onClick={() => setTab(t)}>
            {t === "assistant" ? "Ask the assistant" : t === "overview" ? "Approved handover" : "Sources"}
          </button>
        ))}
      </div>

      {tab === "overview" && (
        <div className="stack reading" role="tabpanel" style={{ gap: 24 }}>
          {handover.loading ? (
            <Spinner />
          ) : handover.error ? (
            <ErrorAlert error={handover.error} />
          ) : handover.data?.approvedContent ? (
            <>
              <div className="alert alert-info">
                <span>
                  Approved by {handover.data.reviewedBy?.displayName} on {formatDateTime(handover.data.approvedAt)}. Written by {handover.data.outgoing.displayName}. Chips show how each item is known.
                </span>
              </div>
              <HandoverView content={handover.data.approvedContent} />
            </>
          ) : (
            <Empty title="The handover is not approved yet">You will see it here as soon as your manager approves it. Until then, the assistant answers from project documents only.</Empty>
          )}
        </div>
      )}
      {tab === "assistant" && <Assistant projectId={p.id} />}
      {tab === "sources" && <Sources projectId={p.id} />}
    </>
  );
}

const KIND: Record<AssistantAnswer["statements"][number]["kind"], { tone: "ok" | "info" | "accent" | "warn"; label: string; help: string }> = {
  verified: { tone: "ok", label: "Verified", help: "Supported by a project document or a confirmed handover item" },
  reported: { tone: "info", label: "Reported", help: "Stated by the outgoing employee in the approved handover" },
  recommendation: { tone: "accent", label: "AI suggestion", help: "Advice generated by the assistant" },
  unanswered: { tone: "warn", label: "Not answered", help: "No supporting evidence found" },
};

const SUGGESTIONS = [
  "What is the purpose and current status of this project?",
  "What are the highest-priority pending tasks?",
  "Which deliverables are blocked?",
  "What are the deployment steps?",
  "Who should I contact when something goes wrong?",
  "What should I focus on during my first week?",
];

function Assistant({ projectId }: { projectId: string }) {
  const { user } = useAuth();
  const history = useLoad(() => get<AssistantAnswer[]>(`/api/projects/${projectId}/assistant/history`), [projectId]);
  const [question, setQuestion] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<unknown>(null);
  const endRef = useRef<HTMLDivElement>(null);

  // Block body on purpose: newer browsers return a Promise from scrollIntoView, which must not
  // become the effect's cleanup value.
  useEffect(() => {
    endRef.current?.scrollIntoView({ block: "end" });
  }, [history.data?.length]);

  const ask = async (q: string) => {
    if (q.trim().length < 3) return;
    setBusy(true);
    setError(null);
    try {
      const a = await post<AssistantAnswer>(`/api/projects/${projectId}/assistant/ask`, { question: q.trim() });
      history.setData([...(history.data ?? []), a]);
      setQuestion("");
    } catch (e) {
      setError(e);
    } finally {
      setBusy(false);
    }
  };

  const provider = history.data?.at(-1)?.provider;

  return (
    <div className="stack reading" role="tabpanel" style={{ gap: 24 }}>
      <div className="card-head">
        <h2>Ask about this project</h2>
        {provider && <Chip tone={provider.generative ? "ok" : "warn"} title={provider.label}>{provider.generative ? provider.label : "Extractive mode: quotes sources only"}</Chip>}
      </div>
      <p className="small muted">Answers come only from the approved handover and the project documents you are allowed to open. Every fact links to its source.</p>
      {history.loading && !history.data ? (
        <Spinner />
      ) : (
        <div className="chat" aria-live="polite">
          {(history.data ?? []).length === 0 && (
            <Empty title="No questions yet">Pick a suggestion below or type your own question.</Empty>
          )}
          {(history.data ?? []).map((a) => (
            <AnswerView key={a.id} a={a} projectId={projectId} asker={user?.displayName ?? "You"} />
          ))}
          {busy && <Spinner label="Searching sources" />}
          <div ref={endRef} />
        </div>
      )}
      <ErrorAlert error={error} />
      {(() => {
        const asked = new Set((history.data ?? []).map((a) => a.question));
        const open = SUGGESTIONS.filter((s) => !asked.has(s));
        return open.length > 0 ? (
          <div className="stack" style={{ gap: 8 }}>
            <span className="eyebrow">Suggested questions</span>
            <div className="suggestions">
              {open.map((s) => (
                <button key={s} onClick={() => void ask(s)} disabled={busy}>{s}</button>
              ))}
            </div>
          </div>
        ) : null;
      })()}
      <form
        className="composer"
        onSubmit={(e) => {
          e.preventDefault();
          void ask(question);
        }}
      >
        <label htmlFor="ask" className="visually-hidden">Your question</label>
        <textarea
          id="ask"
          value={question}
          maxLength={1000}
          onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey) {
              e.preventDefault();
              void ask(question);
            }
          }}
          placeholder="Ask about the project, client, tasks, procedures…"
        />
        <button className="btn btn-primary" type="submit" disabled={busy || question.trim().length < 3}>{busy ? "Searching…" : "Ask"}</button>
      </form>
    </div>
  );
}

function AnswerView({ a, projectId, asker }: { a: AssistantAnswer; projectId: string; asker: string }) {
  return (
    <article className="exchange" aria-label={`Question: ${a.question}`}>
      <div className="msg-q">
        <Avatar name={asker} size="sm" />
        <h3>{a.question}</h3>
      </div>
      <div className="msg-a">
        {a.statements.map((s, i) => (
          <div className="stmt" key={i}>
            {(i === 0 || a.statements[i - 1]!.kind !== s.kind) && (
              <Chip tone={KIND[s.kind].tone} title={KIND[s.kind].help}>{KIND[s.kind].label}</Chip>
            )}
            <p>
              {s.text}
              {s.citations.map((c) => (
                <a key={c} className="cite-ref" href={`#${a.id}-${c}`} aria-label={`Source ${c.replace("S", "")}`}>{c.replace("S", "")}</a>
              ))}
            </p>
          </div>
        ))}
        {a.warnings.map((w, i) => (
          <div key={i} className="alert alert-warn">
            <span>{w.message}{w.citations.length > 0 && ` (sources ${w.citations.map((c) => c.replace("S", "")).join(", ")})`}</span>
          </div>
        ))}
        {a.suggestedContacts.length > 0 && (
          <div className="alert alert-info">
            <span>Ask {a.suggestedContacts.map((c) => `${c.name} (${c.role})`).join(" or ")} for this information.</span>
          </div>
        )}
        {a.citations.length > 0 && (
          <ol className="sources" aria-label="Sources" style={{ listStyle: "none", margin: 0, paddingLeft: 0 }}>
            {a.citations.map((c) => (
              <li className="source" key={c.label} id={`${a.id}-${c.label}`}>
                <span className="row" style={{ gap: 8 }}>
                  <span className="cite-ref" style={{ verticalAlign: "baseline", marginLeft: 0 }}>{c.label.replace("S", "")}</span>
                  <Link to={`/projects/${projectId}/documents/${c.documentId}`}>{c.documentName}</Link>
                  {c.heading && <span className="muted">› {c.heading}</span>}
                  {c.docType === "handover" && <Chip tone="info">Approved handover</Chip>}
                  {c.stale && <Chip tone="warn">May be outdated</Chip>}
                  {c.simulatedSource && <Chip tone="neutral" title="Stored in the mock SharePoint adapter">Mock SharePoint</Chip>}
                </span>
                <span className="muted">
                  {c.versionLabel && `Version ${c.versionLabel} · `}Updated {formatDate(c.lastModifiedAt)}
                  {c.webUrl && (
                    <>
                      {" · "}
                      <a href={c.webUrl} target="_blank" rel="noreferrer">Open in SharePoint</a>
                    </>
                  )}
                </span>
              </li>
            ))}
          </ol>
        )}
        <span className="small muted">Answered {formatDateTime(a.createdAt)}</span>
      </div>
    </article>
  );
}

function Sources({ projectId }: { projectId: string }) {
  const docs = useLoad(() => get<DocumentSummary[]>(`/api/projects/${projectId}/documents`), [projectId]);
  if (docs.loading && !docs.data) return <Spinner />;
  if (docs.error) return <ErrorAlert error={docs.error} />;
  const list = docs.data ?? [];
  return (
    <div className="stack reading" role="tabpanel" style={{ gap: 24 }}>
      <h2>Indexed sources</h2>
      <p className="small muted">Documents from the project's SharePoint folder that you have permission to read.</p>
      {list.length === 0 ? (
        <Empty title="No documents indexed yet" />
      ) : (
        <div className="table-wrap">
          <table>
            <thead>
              <tr><th>Document</th><th>Type</th><th>Updated</th><th>Index status</th></tr>
            </thead>
            <tbody>
              {list.map((d) => (
                <tr key={d.id}>
                  <td>
                    {d.ingestStatus === "indexed" ? <Link to={`/projects/${projectId}/documents/${d.id}`}>{d.name}</Link> : d.name}
                    {d.superseded && <div><Chip tone="neutral">Superseded</Chip></div>}
                  </td>
                  <td>{d.docType.replace("_", " ")}</td>
                  <td className="num">{formatDate(d.lastModifiedAt)}</td>
                  <td>
                    {d.ingestStatus === "indexed" && <Chip tone="ok">Indexed</Chip>}
                    {d.ingestStatus === "unsupported_format" && <Chip tone="neutral" title="Office and PDF extraction is not available yet">Format not supported</Chip>}
                    {d.ingestStatus === "error" && <Chip tone="danger" title={d.ingestError ?? ""}>Error</Chip>}
                    {d.flaggedChunks > 0 && <div><Chip tone="warn" title="Passages with instruction-like text are withheld from the assistant">{d.flaggedChunks} passage(s) withheld</Chip></div>}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
